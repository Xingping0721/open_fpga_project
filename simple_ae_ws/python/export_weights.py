"""
weights/ae_weights.npz を読み込み、Q8.8固定小数点に変換して
rtl/ae_params.vh (localparam) に書き出すスクリプト。

同時に、Verilogと全く同じ整数演算(乗算・加算・算術右シフト>>>8による
Q16.16 -> Q8.8変換)で推論するリファレンスモデルを実行し、
infer.py と同じ入力サンプル(正弦波、phase=0.7)に対する期待値を
tb/expected_vectors.vh に書き出す。

- date : 20/09/2026
- author : Kohei Yoshii
"""

import os
import numpy as np

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
WORKSPACE_DIR = os.path.dirname(SCRIPT_DIR)  # simple_ae_ws/
WEIGHTS_PATH = os.path.join(SCRIPT_DIR, "weights", "ae_weights.npz")
RTL_DIR = os.path.join(WORKSPACE_DIR, "rtl")
TB_DIR = os.path.join(WORKSPACE_DIR, "tb")

INPUT_DIM = 8
LATENT_DIM = 4
OUTPUT_DIM = 8

LEAKY_ALPHA = 0.01  # train.py / infer.py と必ず同じ値にすること

# ---------------------------------------------------------
# 1. Q8.8 固定小数点への量子化
# ---------------------------------------------------------
def to_q8_8(value):
    """round(value * 256) を int16 範囲 [-32768, 32767] にクリップして返す。"""
    q = int(np.round(value * 256))
    return int(np.clip(q, -32768, 32767))


def fmt_hex16(q):
    """符号あり16bit整数を Verilog の 16'sh.... 表記に変換する。"""
    return "16'sh%04X" % (q & 0xFFFF)


# ---------------------------------------------------------
# 2. 重みの読み込み・量子化
# ---------------------------------------------------------
data = np.load(WEIGHTS_PATH)
W_enc = data["W_enc"]  # (8, 4)  W_enc[i, j] : 入力i -> 潜在j
b_enc = data["b_enc"]  # (4,)
W_dec = data["W_dec"]  # (4, 8)  W_dec[j, k] : 潜在j -> 出力k
b_dec = data["b_dec"]  # (8,)

W_enc_q = np.vectorize(to_q8_8)(W_enc)
b_enc_q = np.vectorize(to_q8_8)(b_enc)
W_dec_q = np.vectorize(to_q8_8)(W_dec)
b_dec_q = np.vectorize(to_q8_8)(b_dec)

ALPHA_Q = to_q8_8(LEAKY_ALPHA)  # 0.01 * 256 = 2.56 -> round -> 3 (16'sh0003)

# ---------------------------------------------------------
# 3. rtl/ae_params.vh の書き出し
# ---------------------------------------------------------
os.makedirs(RTL_DIR, exist_ok=True)
os.makedirs(TB_DIR, exist_ok=True)

lines = []
lines.append("// Auto-generated by python/export_weights.py")
lines.append("// Q8.8 fixed-point parameters for the 8-4-8 autoencoder")
lines.append("// DO NOT EDIT BY HAND - regenerate with export_weights.py")
lines.append("")
lines.append("localparam signed [15:0] ALPHA_Q8_8 = %s;" % fmt_hex16(ALPHA_Q))
lines.append("")

lines.append("// Encoder weights: W_ENC_<in><latent>  (input i -> latent j)")
for j in range(LATENT_DIM):
    for i in range(INPUT_DIM):
        lines.append(
            "localparam signed [15:0] W_ENC_%d%d = %s;"
            % (i, j, fmt_hex16(W_enc_q[i, j]))
        )
lines.append("")
lines.append("// Encoder biases")
for j in range(LATENT_DIM):
    lines.append(
        "localparam signed [15:0] B_ENC_%d = %s;" % (j, fmt_hex16(b_enc_q[j]))
    )
lines.append("")

lines.append("// Decoder weights: W_DEC_<latent><out>  (latent j -> output k)")
for k in range(OUTPUT_DIM):
    for j in range(LATENT_DIM):
        lines.append(
            "localparam signed [15:0] W_DEC_%d%d = %s;"
            % (j, k, fmt_hex16(W_dec_q[j, k]))
        )
lines.append("")
lines.append("// Decoder biases")
for k in range(OUTPUT_DIM):
    lines.append(
        "localparam signed [15:0] B_DEC_%d = %s;" % (k, fmt_hex16(b_dec_q[k]))
    )
lines.append("")

ae_params_path = os.path.join(RTL_DIR, "ae_params.vh")
with open(ae_params_path, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", ae_params_path)


# ---------------------------------------------------------
# 4. Verilogと同一の整数演算によるリファレンスモデル
# ---------------------------------------------------------
def q_leaky_relu(x_q):
    """x_q: Q8.8 の整数値。Verilogのleaky_relu.vと同じ演算。"""
    if x_q >= 0:
        return x_q
    prod = x_q * ALPHA_Q          # Q8.8 * Q8.8 = Q16.16
    return prod >> 8              # 算術右シフトでQ8.8に戻す(Pythonのint>>は算術シフト)


def q_neuron(x_qs, w_qs, b_q):
    """
    x_qs, w_qs: 同じ長さのQ8.8整数リスト
    b_q: Q8.8整数のバイアス
    Verilogのneuron_enc.v/neuron_dec.vと同じMAC演算を行い、
    leaky_relu適用後のQ8.8整数を返す。
    """
    acc = 0  # Q16.16
    for x_q, w_q in zip(x_qs, w_qs):
        acc += x_q * w_q          # Q8.8 * Q8.8 = Q16.16
    acc += b_q << 8                # Q8.8 -> Q16.16 に揃えて加算
    z_pre_q = acc >> 8             # Q16.16 -> Q8.8
    return q_leaky_relu(z_pre_q)


def q_forward(x_qs):
    """8個のQ8.8整数入力から、8個のQ8.8整数出力を計算する。"""
    z_qs = []
    for j in range(LATENT_DIM):
        w_qs = [int(W_enc_q[i, j]) for i in range(INPUT_DIM)]
        z_qs.append(q_neuron(x_qs, w_qs, int(b_enc_q[j])))

    y_qs = []
    for k in range(OUTPUT_DIM):
        w_qs = [int(W_dec_q[j, k]) for j in range(LATENT_DIM)]
        y_qs.append(q_neuron(z_qs, w_qs, int(b_dec_q[k])))

    return y_qs, z_qs


# ---------------------------------------------------------
# 5. infer.py と同じ入力サンプル(正弦波、phase=0.7)を生成
# ---------------------------------------------------------
t = np.linspace(0, 2 * np.pi, INPUT_DIM, endpoint=False)
phase = 0.7
x_float = 0.5 * (np.sin(t + phase) + 1.0)

x_qs = [to_q8_8(v) for v in x_float]
y_qs, z_qs = q_forward(x_qs)

# ---------------------------------------------------------
# 6. tb/expected_vectors.vh の書き出し
# ---------------------------------------------------------
tb_lines = []
tb_lines.append("// Auto-generated by python/export_weights.py")
tb_lines.append("// Test vector (sine wave, phase=0.7) and expected outputs (Q8.8)")
tb_lines.append("// DO NOT EDIT BY HAND - regenerate with export_weights.py")
tb_lines.append("")
for i, q in enumerate(x_qs):
    tb_lines.append("localparam signed [15:0] TEST_X_%d = %s;" % (i, fmt_hex16(q)))
tb_lines.append("")
for k, q in enumerate(y_qs):
    tb_lines.append(
        "localparam signed [15:0] EXPECTED_Y_%d = %s;" % (k, fmt_hex16(q))
    )
tb_lines.append("")

expected_path = os.path.join(TB_DIR, "expected_vectors.vh")
with open(expected_path, "w") as f:
    f.write("\n".join(tb_lines) + "\n")
print("wrote", expected_path)

# ---------------------------------------------------------
# 7. 参考表示 (float版 infer.py の結果と比較できるように)
# ---------------------------------------------------------
np.set_printoptions(precision=6, suppress=True)
print()
print("input (x)          :", x_float)
print("input (x, Q8.8)     :", x_qs)
print("latent (z, Q8.8)    :", z_qs)
print("output (y, Q8.8)    :", y_qs)
print("output (y, float)   :", [q / 256.0 for q in y_qs])
